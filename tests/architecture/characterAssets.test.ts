/** Where every drawn vertex of a character is, posed: the silhouette the markers and the hit tests rely on. */
function drawnBox(root: Object3D, hiddenNodes: readonly string[]): Box3 {
  root.updateMatrixWorld(true);
  const box = new Box3();
  const vertex = new Vector3();
  const visit = (node: Object3D): void => {
    if (hiddenNodes.includes(node.name)) return;
    if (node instanceof SkinnedMesh) node.skeleton.update();
    if (node instanceof Mesh) {
      const position = node.geometry.getAttribute('position');
      for (let i = 0; i < position.count; i++) {
        vertex.fromBufferAttribute(position, i);
        if (node instanceof SkinnedMesh) node.applyBoneTransform(i, vertex);
        box.expandByPoint(vertex.applyMatrix4(node.matrixWorld));
      }
    }
    for (const child of node.children) visit(child);
  };
  visit(root);
  return box;
}

/** How far below the floor a clip may dip for a frame, in metres: a shoe in the floor, not a sunk body. */
const FLOOR_SLACK_M = 0.03;

describe('the silhouettes are gameplay (story 7.2, D8)', () => {
  const eachClipPose = (
    asset: Awaited<ReturnType<typeof load>>,
    visit: (clip: string, atS: number) => void,
  ): void => {
    const mixer = new AnimationMixer(asset.scene);
    for (const clip of asset.animations) {
      const action = mixer.clipAction(clip).play();
      for (const share of [0.25, 0.5, 0.75]) {
        mixer.setTime(clip.duration * share);
        visit(clip.name, clip.duration * share);
      }
      action.stop();
    }
    mixer.stopAllAction();
  };

  it('Papa stands on the floor, his head at PAPA_HEIGHT_M, about 2 × papaRadiusM wide', async () => {
    const asset = await load('papa');
    const box = drawnBox(asset.scene, PAPA_CONTRACT.hiddenNodes);
    expect(box.min.y).toBeCloseTo(0, 1);
    expect(box.max.y).toBeLessThanOrEqual(PAPA_HEIGHT_M);
    expect(box.max.y).toBeGreaterThan(PAPA_HEIGHT_M - 0.03);
    expect(box.max.x - box.min.x).toBeGreaterThan(0.4);
    expect(box.max.x - box.min.x).toBeLessThan(0.56);
  });

  it('no clip of Papa sinks him into the floor', async () => {
    const asset = await load('papa');
    eachClipPose(asset, (clip) => {
      expect(drawnBox(asset.scene, PAPA_CONTRACT.hiddenNodes).min.y, clip).toBeGreaterThan(
        -FLOOR_SLACK_M,
      );
    });
  });

  it('the baby stands about 2 × bodyRadiusM tall, with his centre of mass where the sphere had it', async () => {
    const asset = await load('baby');
    const box = drawnBox(asset.scene, BABY_CONTRACT.hiddenNodes);
    expect(box.min.y).toBeCloseTo(0, 1);
    expect(box.max.y).toBeCloseTo(0.4, 1);
    expect((box.min.y + box.max.y) / 2).toBeCloseTo(0.2, 1);
  });

  it('no clip lifts the baby above the 0.9 m sofa he hides behind, or sinks him', async () => {
    const asset = await load('baby');
    eachClipPose(asset, (clip) => {
      const box = drawnBox(asset.scene, BABY_CONTRACT.hiddenNodes);
      expect(box.max.y, clip).toBeLessThan(0.9);
      expect(box.min.y, clip).toBeGreaterThan(-FLOOR_SLACK_M);
    });
  });
});

/** How far an accessory may stand off the part it belongs to, in metres: a mug in a raised hand, spikes of hair. */
const ACCESSORY_SLACK_M = 0.1;

describe("Papa's look and accessories sit where the view shows them (story 7.2, AC 6)", () => {
  // The hidden nodes are skipped by every silhouette test above, so these are the ones that say where
  // they stand. Each is measured posed, as the view shows it: the mug in `drink`, the handset in `on_phone`.
  const posed = async (clip: string | null) => {
    const asset = await load('papa');
    if (clip !== null) {
      const found = asset.animations.find((candidate) => candidate.name === clip);
      if (found === undefined) throw new Error(`papa.glb has no clip "${clip}"`);
      const mixer = new AnimationMixer(asset.scene);
      mixer.clipAction(found).play();
      mixer.setTime(found.duration / 2);
    }
    asset.scene.updateMatrixWorld(true);
    const part = (name: string): Box3 => {
      const node = asset.scene.getObjectByName(name);
      if (node === undefined) throw new Error(`papa.glb has no node "${name}"`);
      // The steam is the mug's child: the mug's own box leaves it out (story 2.13).
      return drawnBox(node, name === 'papa_mug_steam' ? [] : ['papa_mug_steam']);
    };
    return { asset, part, body: drawnBox(asset.scene, PAPA_CONTRACT.hiddenNodes) };
  };
  const within = (outer: Box3, inner: Box3, slackM: number): boolean =>
    outer.clone().expandByScalar(slackM).containsBox(inner);
  /** A held thing may stand out of the body's box (a mug at arm's length) but must meet it. */
  const touches = (outer: Box3, held: Box3, slackM: number): boolean =>
    outer.clone().expandByScalar(slackM).intersectsBox(held);

  it('wears the primary colour of DESIGN.md, so that he stays the purple one', async () => {
    const { asset } = await posed(null);
    const colours: string[] = [];
    asset.scene.getObjectByName('papa_shirt')?.traverse((node) => {
      if (!(node instanceof Mesh)) return;
      const hex = (node.material as { color: { getHex(): number } }).color.getHex();
      colours.push(`#${hex.toString(16).padStart(6, '0')}`);
    });
    expect(colours).toContain(colourToken('primary').toLowerCase());
  });

  it('raises the mug to his head while he drinks', async () => {
    const { part, body } = await posed('drink');
    const mug = part('papa_mug');
    expect(touches(body, mug, ACCESSORY_SLACK_M)).toBe(true);
    expect((mug.min.y + mug.max.y) / 2).toBeGreaterThan(0.45);
  });

  it('holds the handset by his head while he is on the phone', async () => {
    const { part, body } = await posed('on_phone');
    const handset = part('papa_handset');
    expect(touches(body, handset, ACCESSORY_SLACK_M)).toBe(true);
    expect((handset.min.y + handset.max.y) / 2).toBeGreaterThan(0.55);
  });

  it('stands the hair on his head, over his width', async () => {
    const { part, body } = await posed(null);
    const hair = part('papa_hair');
    expect(hair.min.y).toBeGreaterThan(PAPA_HEIGHT_M - 0.15);
    expect(hair.min.x).toBeGreaterThan(body.min.x - ACCESSORY_SLACK_M);
    expect(hair.max.x).toBeLessThan(body.max.x + ACCESSORY_SLACK_M);
  });

  it('puts the mash on his face and the inside-out shirt where the shirt is', async () => {
    const { part, body } = await posed(null);
    expect(within(body, part('papa_look_mash'), ACCESSORY_SLACK_M)).toBe(true);
    expect(within(part('papa_shirt'), part('papa_look_shirt'), 0.03)).toBe(true);
  });
});

/** Story 7.2's props, longest side of the box at rest, in metres: story 2.13 makes each at least twice as big (AC 1, 6). */
const MUG_LONGEST_SIDE_7_2_M = 0.218;
const HANDSET_LONGEST_SIDE_7_2_M = 0.32;
const PROP_SIZE_FACTOR_MIN = 2;
/** The eyes widen to at least this scale at the kick's peak (AC 5). */
const EYES_WIDEST_SCALE_MIN = 1.4;

describe("Papa's exaggerated props and poses (story 2.13)", () => {
  const posed = async (clip: string | null) => {
    const asset = await load('papa');
    if (clip !== null) {
      const found = asset.animations.find((candidate) => candidate.name === clip);
      if (found === undefined) throw new Error(`papa.glb has no clip "${clip}"`);
      const mixer = new AnimationMixer(asset.scene);
      mixer.clipAction(found).play();
      mixer.setTime(found.duration / 2);
    }
    asset.scene.updateMatrixWorld(true);
    const part = (name: string): Box3 => {
      const node = asset.scene.getObjectByName(name);
      if (node === undefined) throw new Error(`papa.glb has no node "${name}"`);
      return drawnBox(node, name === 'papa_mug_steam' ? [] : ['papa_mug_steam']);
    };
    return { asset, part };
  };
  const longestSideOf = (box: Box3): number => {
    const size = box.getSize(new Vector3());
    return Math.max(size.x, size.y, size.z);
  };

  it('has a mug at least twice as big as in story 7.2', async () => {
    const { part } = await posed(null);
    expect(longestSideOf(part('papa_mug'))).toBeGreaterThanOrEqual(
      PROP_SIZE_FACTOR_MIN * MUG_LONGEST_SIDE_7_2_M,
    );
  });

  it('has a handset at least twice as big as in story 7.2', async () => {
    const { part } = await posed(null);
    expect(longestSideOf(part('papa_handset'))).toBeGreaterThanOrEqual(
      PROP_SIZE_FACTOR_MIN * HANDSET_LONGEST_SIDE_7_2_M,
    );
  });

  it("stands the steam above the mug's rim while he drinks", async () => {
    const { part } = await posed('drink');
    const mug = part('papa_mug');
    const steam = part('papa_mug_steam');
    expect(steam.isEmpty()).toBe(false);
    expect((steam.min.y + steam.max.y) / 2).toBeGreaterThan(mug.max.y - 0.02);
  });

  it('hangs the steam under the mug, so that it shows and hides with the mug', async () => {
    const { asset } = await posed(null);
    const steam = asset.scene.getObjectByName('papa_mug_steam');
    expect(steam?.parent?.name).toBe('papa_mug');
  });

  it('widens his eyes to at least 1.4 in coffee_kick, and in no other clip', async () => {
    const asset = await load('papa');
    const eyesTracks = (clip: string) =>
      (asset.animations.find((candidate) => candidate.name === clip)?.tracks ?? []).filter(
        (track) => track.name.startsWith('eyes.'),
      );
    const kick = eyesTracks('coffee_kick').find((track) => track.name === 'eyes.scale');
    expect(kick, 'coffee_kick keys the scale of `eyes`').toBeDefined();
    expect(Math.max(...(kick?.values ?? [0]))).toBeGreaterThanOrEqual(EYES_WIDEST_SCALE_MIN);
    // Up, then back: each axis starts and ends at rest and peaks in the middle of the clip.
    const values = kick?.values ?? [];
    const keyCount = values.length / 3;
    expect(keyCount).toBeGreaterThanOrEqual(3);
    for (let axis = 0; axis < 3; axis++) {
      const keys = Array.from({ length: keyCount }, (_, key) => values[key * 3 + axis] as number);
      expect(keys[0], `axis ${axis} starts at rest`).toBeCloseTo(1, 3);
      expect(keys[keyCount - 1], `axis ${axis} returns to rest`).toBeCloseTo(1, 3);
      expect(Math.max(...keys), `axis ${axis} widens`).toBeGreaterThanOrEqual(
        EYES_WIDEST_SCALE_MIN,
      );
      const peakKey = keys.indexOf(Math.max(...keys));
      expect(peakKey, `axis ${axis} peaks mid-clip`).toBeGreaterThan(0);
      expect(peakKey, `axis ${axis} peaks mid-clip`).toBeLessThan(keyCount - 1);
    }
    const others = asset.animations.filter((clip) => clip.name !== 'coffee_kick');
    expect(others.length).toBeGreaterThan(10);
    for (const clip of others) expect(eyesTracks(clip.name), clip.name).toEqual([]);
  });

  it('keys nothing the code moves: not the steam, not the bubble, not the lids', async () => {
    const asset = await load('papa');
    expect(asset.animations.length).toBeGreaterThan(10);
    for (const clip of asset.animations) {
      for (const track of clip.tracks) {
        expect(track.name, clip.name).not.toMatch(/^(papa_mug_steam|papa_blabla|eyelids)\./);
      }
    }
  });
});

