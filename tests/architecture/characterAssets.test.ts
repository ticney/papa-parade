/** Where every drawn vertex of a character is, posed: the silhouette the markers and the hit tests rely on. */
function drawnBox(root: Object3D, hiddenNodes: readonly string[]): Box3 {
  root.updateMatrixWorld(true);
  const box = new Box3();
  const vertex = new Vector3();
  const visit = (node: Object3D): void => {
    if (hiddenNodes.includes(node.name)) return;
    if (node instanceof SkinnedMesh) node.skeleton.update();
    if (node instanceof Mesh) {
      const position = node.geometry.getAttribute('position');
      for (let i = 0; i < position.count; i++) {
        vertex.fromBufferAttribute(position, i);
        if (node instanceof SkinnedMesh) node.applyBoneTransform(i, vertex);
        box.expandByPoint(vertex.applyMatrix4(node.matrixWorld));
      }
    }
    for (const child of node.children) visit(child);
  };
  visit(root);
  return box;
}

