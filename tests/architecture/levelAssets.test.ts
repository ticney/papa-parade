import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { isVisualNodeName } from '../../src/content/levelNodeNames.ts';
import { parseContentFile } from '../../src/content/parseContentFile.ts';
import { FeedbackTableSchema } from '../../src/content/schemas/feedback.ts';
import { LevelGeometrySchema } from '../../src/content/schemas/levelGeometry.ts';
import {
  LEVEL_PAYLOAD_MAX_BYTES,
  LEVEL_PAYLOAD_MAX_BYTES_BY_ID,
  ROOM_DRAW_CALLS_MAX,
  ROOM_TRIANGLES_MAX,
} from '../../src/shared/constants.ts';
import { parseGlb } from '../../tools/assets/glb.ts';
import {
  floorContrastProblem,
  floorLightOf,
  reservedHueProblems,
  roomBudgetOf,
  roomMaterialProblems,
} from '../../tools/assets/roomArt.ts';
import { expectedTokens } from './designTokens.ts';
import { extractFrontmatter, parseYamlSubset } from './yamlSubset.ts';

// The committed level artefacts: the shipped .glb (NFR3: at most 3 MB) and the geometry the sim
// will read. CI has no Blender: these files are generated by `npm run assets:export`,
// `assets:extract` and `assets:optimize`, then committed.

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const levelIds = readdirSync(join(root, 'content', 'levels'))
  .filter((name) => name.endsWith('.json') && !name.endsWith('.geometry.json'))
  .map((name) => name.slice(0, -'.json'.length));

const designTokens = expectedTokens(
  parseYamlSubset(
    extractFrontmatter(
      readFileSync(
        join(
          root,
          '_bmad-output',
          'planning-artifacts',
          'ux-designs',
          'ux-papa-parade-2026-10-26',
          'DESIGN.md',
        ),
        'utf8',
      ),
    ),
  ),
);
/** The side of the floor's slab: part of the `floor` node, but no wave is drawn on it (story 7.3, D8). */
const FLOOR_SLAB_SIDES = ['art_wood'];
const feedbackFile = parseContentFile(
  'content/feedback.json',
  readFileSync(join(root, 'content', 'feedback.json'), 'utf8'),
  FeedbackTableSchema,
);
if (!feedbackFile.ok) throw new Error('content/feedback.json does not parse');
const { render } = feedbackFile.value;
function colourToken(name: string): string {
  const token = designTokens.find((candidate) => candidate.name === `--pp-color-${name}`);
  if (token === undefined) throw new Error(`DESIGN.md has no colour "${name}"`);
  return token.value;
}

interface GltfNode {
  name?: string;
  mesh?: number;
  children?: number[];
}

/** Does the node, or anything under it, carry a mesh? (gltfpack may move the mesh to a child.) */
function holdsMesh(nodes: GltfNode[], index: number): boolean {
  const node = nodes[index];
  if (node === undefined) return false;
  return node.mesh !== undefined || (node.children ?? []).some((child) => holdsMesh(nodes, child));
}

describe('the per-level payload budgets (NFR15)', () => {
  it('names only committed levels', () => {
    // A typo or a renamed level would otherwise fall back to the 3 MiB budget without a word.
    for (const id of Object.keys(LEVEL_PAYLOAD_MAX_BYTES_BY_ID)) {
      expect(levelIds, `the budget of "${id}"`).toContain(id);
    }
  });

  it('only raises the default budget', () => {
    for (const [id, budgetBytes] of Object.entries(LEVEL_PAYLOAD_MAX_BYTES_BY_ID)) {
      expect(budgetBytes, `the budget of "${id}"`).toBeGreaterThan(LEVEL_PAYLOAD_MAX_BYTES);
    }
  });
});

describe.each(levelIds)('the committed %s level', (levelId) => {
  const glbFile = join(root, 'public', 'assets', 'levels', `${levelId}.glb`);
  const geometryFile = join(root, 'content', 'levels', `${levelId}.geometry.json`);

  it('ships a .glb within the payload ceiling', () => {
    // The level's own budget (NFR15), as `dist:check` reads it.
    const budgetBytes = Object.hasOwn(LEVEL_PAYLOAD_MAX_BYTES_BY_ID, levelId)
      ? (LEVEL_PAYLOAD_MAX_BYTES_BY_ID[levelId] as number)
      : LEVEL_PAYLOAD_MAX_BYTES;
    expect(statSync(glbFile).size).toBeLessThanOrEqual(budgetBytes);
  });

  it('has a geometry file that passes LevelGeometrySchema', () => {
    const text = readFileSync(geometryFile, 'utf8');
    const parsed = parseContentFile(
      `content/levels/${levelId}.geometry.json`,
      text,
      LevelGeometrySchema,
    );
    expect(parsed).toMatchObject({ ok: true });
    if (parsed.ok) expect(parsed.value.id).toBe(levelId);
  });

  it('still holds at least one visual mesh node', () => {
    const { json } = parseGlb(new Uint8Array(readFileSync(glbFile)));
    const nodes = (json as { nodes?: GltfNode[] }).nodes ?? [];
    const visuals = nodes.flatMap((node, index) =>
      node.name !== undefined && isVisualNodeName(node.name) && holdsMesh(nodes, index)
        ? [node.name]
        : [],
    );
    expect(visuals.length).toBeGreaterThan(0);
  });

  it('stays within the budget of one room', () => {
    const { json } = parseGlb(new Uint8Array(readFileSync(glbFile)));
    const budget = roomBudgetOf(json);
    expect(budget.drawCalls).toBeLessThanOrEqual(ROOM_DRAW_CALLS_MAX);
    expect(budget.triangles).toBeLessThanOrEqual(ROOM_TRIANGLES_MAX);
  });

  it('keeps off the hues reserved for gameplay', () => {
    const { json } = parseGlb(new Uint8Array(readFileSync(glbFile)));
    const reserved = ['parry', 'dodge', 'alert'].map(colourToken);
    expect(reservedHueProblems(json, reserved)).toEqual([]);
  });

  it('keeps its colour to a few base-colour materials', () => {
    const { json } = parseGlb(new Uint8Array(readFileSync(glbFile)));
    expect(roomMaterialProblems(json)).toEqual([]);
  });

  it('has a floor the ink of the sound waves shows on, as authored', () => {
    const { json } = parseGlb(new Uint8Array(readFileSync(glbFile)));
    expect(floorContrastProblem(json, colourToken('ink'))).toBeNull();
  });

  it('has walkable planks the ink shows on, under its own lights', () => {
    const { json } = parseGlb(new Uint8Array(readFileSync(glbFile)));
    const lights = render.lights.byLevel[levelId] ?? render.lights.default;
    const light = floorLightOf(lights, render.toonTones, render.sunOffsetM);
    expect(floorContrastProblem(json, colourToken('ink'), light, FLOOR_SLAB_SIDES)).toBeNull();
  });
});

describe('the lights of feedback.json', () => {
  const rows = [render.lights.default, ...Object.values(render.lights.byLevel)];
  const toLinear = (channel: number): number =>
    channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;

  it.each(rows.flatMap((row) => [row.ambientColor, row.sunColor]))(
    '%s is not vivid on a hue reserved for gameplay',
    (hex) => {
      const channels = [1, 3, 5].map((at) =>
        toLinear(Number.parseInt(hex.slice(at, at + 2), 16) / 255),
      );
      const fixture = {
        materials: [{ name: hex, pbrMetallicRoughness: { baseColorFactor: [...channels, 1] } }],
      };
      const reserved = ['parry', 'dodge', 'alert'].map(colourToken);
      expect(reservedHueProblems(fixture, reserved)).toEqual([]);
    },
  );
});
